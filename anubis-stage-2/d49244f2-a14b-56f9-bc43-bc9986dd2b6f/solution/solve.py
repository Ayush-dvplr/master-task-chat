#!/usr/bin/env python3
"""Assessment program for the Consolidated Enterprise Levy Code.

Reads the in-force rule table out of levy_code.md in the batch directory, then
computes the nine assessment statements from the registers.
"""

from __future__ import annotations

import csv
import json
import re
import sys
from datetime import date, timedelta
from decimal import ROUND_HALF_EVEN, ROUND_HALF_UP, Decimal
from pathlib import Path
from typing import Any

MONTHS = {m: i + 1 for i, m in enumerate(["January", "February", "March", "April", "May", "June", "July", "August",
                                          "September", "October", "November", "December"])}
WORDS = {"no": 0, "nil": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7}
FUEL_PHRASES = {"electricity supplied from the grid": "grid_electricity", "reticulated natural gas": "natural_gas",
                "diesel and distillate fuel": "diesel", "biomass and wood fuel": "biomass",
                "electricity generated by onsite solar installations": "solar_onsite"}
FORM_PHRASES = {"an individual carrying on business as a sole trader": "sole_trader", "a partnership": "partnership",
                "a company": "company", "a trust": "trust", "a cooperative society": "cooperative", "a statutory body": "statutory_body"}
QUARTER_OF = {(1, 1): "Q1", (4, 1): "Q2", (7, 1): "Q3", (10, 1): "Q4"}
LEVY_START, LEVY_END, OPEN = date(2026, 1, 1), date(2026, 12, 31), date(2099, 12, 31)


def sec_order(num: str) -> tuple[int, int]:
    a, b = num.split("-")
    return int(a), int(b)


def parse_date(text: str) -> date:
    d, mon, y = text.split()
    return date(int(y), MONTHS[mon], int(d))


def ppm_of(pct: str) -> int:
    whole, _, frac = pct.partition(".")
    return int(whole) * 10000 + int((frac + "0000")[:4])


def cents_of(text: str) -> int:
    whole, _, frac = text.replace("$", "").replace(",", "").partition(".")
    return int(whole) * 100 + int((frac + "00")[:2])


def mc_of(text: str) -> int:
    whole, _, frac = text.partition(".")
    return int(whole) * 1000 + int((frac + "000")[:3])


def sections(text: str) -> list[dict[str, str]]:
    out = []
    division = ""
    current = None
    for line in text.splitlines():
        if line.startswith("#### "):
            division = line[5:]
            continue
        if line.startswith("## "):
            division = ""
            continue
        m = re.match(r"^### Section (\d+-\d+)\. (.*)$", line)
        if m:
            current = {"num": m.group(1), "title": m.group(2), "division": division, "body": ""}
            out.append(current)
            continue
        if current is not None:
            current["body"] += line + "\n"
    return out


class Table:
    """Provisions collected from the Code: (section, key, op, value, start)."""

    def __init__(self) -> None:
        self.original: list[list] = []
        self.modifying: list[list] = []

    def add(self, original: bool, num: str, key: tuple, op: str, value: Any, start: Any = None) -> None:
        (self.original if original else self.modifying).append([num, key, op, value, start, num])


def read_rules(code_path: Path) -> dict[str, Any]:
    secs = sections(code_path.read_text(encoding="utf-8"))
    tab = Table()
    credits: dict[str, dict[str, Any]] = {}
    holidays: list[str] = []
    corrections: list[tuple[str, str, str, str]] = []
    residual = ""

    for s in secs:
        num, body, title, div = s["num"], s["body"], s["title"], s["division"]
        part = int(num.split("-")[0])
        if div.startswith("Division 7-9"):
            continue
        if part == 14 and "Designation: Binding Ruling." not in body:
            continue
        cm = re.match(r"Class (AC-\d+): ", title)
        if cm and part == 2:
            code = cm.group(1)
            tab.add(True, num, ("rate", code), "set", ppm_of(re.search(r"\(d\)[^\n]*?(\d+\.\d{4}) per cent", body).group(1)))
            e = re.search(r"\(e\) Export receipts\.([^\n]*)", body).group(1)
            tab.add(True, num, ("export", code), "set", ("not excluded" not in e and "No deduction" not in e))
            tab.add(True, num, ("band", code), "set", re.search(r"\(f\)[^\n]*?\bBand (I{1,3})\b", body).group(1))
            continue
        dm = re.match(r"District (D-\d+): ", title)
        if dm and part == 3:
            code = dm.group(1)
            c_line = re.search(r"\(c\) Designations\.([^\n]*)", body).group(1)
            neither = "is not designated a Coastal" in c_line
            tab.add(True, num, ("district", code), "set", cents_of(re.search(r"\(d\)[^\n]*?(\$\d+\.\d{2}) per square metre", body).group(1)))
            tab.add(True, num, ("region", code), "set", re.search(r"part of the (\w+) region", body).group(1))
            tab.add(True, num, ("coastal", code), "set", (not neither) and "Coastal Zone" in c_line)
            tab.add(True, num, ("edz", code), "set", (not neither) and "Enterprise Development Zone" in c_line)
            continue
        if num == "1-090":
            holidays = [parse_date(x).isoformat() for x in re.findall(r"(\d{1,2} [A-Z][a-z]+ \d{4})", body.split("(2)")[0])]
        elif num == "2-040":
            tab.add(True, num, ("se_threshold",), "set", cents_of(re.search(r"exceed (\$[\d,]+)", body).group(1)))
            tab.add(True, num, ("se_factor",), "set", int(re.search(r"computed at (\d+) per cent", body).group(1)))
        elif num == "4-010":
            tab.add(True, num, ("payroll_rate",), "set", ppm_of(re.search(r"(\d+\.\d+) per cent", body).group(1)))
        elif num == "4-020":
            tab.add(True, num, ("payroll_exemption",), "set", cents_of(re.search(r"is (\$[\d,]+)", body).group(1)))
            tab.add(True, num, ("mutual_multiplier",), "set", 1)
        elif num == "5-010":
            for phrase, fuel in FUEL_PHRASES.items():
                m = re.search(r"for " + re.escape(phrase) + r", (\d+\.\d{3}) cents per kilowatt-hour", body)
                tab.add(True, num, ("energy", fuel), "set", mc_of(m.group(1)) if m else 0)
        elif num == "5-020":
            tab.add(True, num, ("band_reduction",), "set", int(re.search(r"by (\d+) per cent", body).group(1)))
        elif num == "6-010":
            for region, pct in re.findall(r"for the (\w+) region, (\d+\.\d{4}) per cent", body):
                tab.add(True, num, ("surcharge", region), "set", ppm_of(pct))
        elif num == "6-020":
            tab.add(True, num, ("coastal_supplement",), "set", ppm_of(re.search(r"(\d+\.\d{4}) per cent", body).group(1)))
        elif num == "8-020":
            tab.add(True, num, ("public_factor",), "set", int(re.search(r"at (\d+) per cent", body).group(1)))
        elif num == "9-001":
            tab.add(True, num, ("global_cap",), "set", int(re.search(r"exceed (\d+) per cent", body).group(1)))
        elif num == "11-010":
            for phrase, form in FORM_PHRASES.items():
                tab.add(True, num, ("minimum", form), "set", cents_of(re.search(rf"for {re.escape(phrase)}, (\$[\d,]+)", body).group(1)))
        elif num == "12-020":
            tab.add(True, num, ("interest",), "set", ppm_of(re.search(r"(\d+\.\d+) per cent", body).group(1)))
        km = re.search(r"establishes the [A-Za-z ]+, identified by credit code (K-\d\d)", body)
        if km and part != 14:
            spec = parse_credit(num, body)
            credits[spec["credit_code"]] = spec
            tab.add(True, num, ("credit_rate", spec["credit_code"]), "set", spec.pop("_rate"))
            tab.add(True, num, ("credit_cap", spec["credit_code"]), "set", spec.pop("_cap"))
            tab.add(True, num, ("credit_carry", spec["credit_code"]), "set", spec.pop("_carry"))
            continue
        if "establishes the residual class" in body:
            residual = re.search(r"Class (AC-\d+)", body).group(1)
            tab.add(True, num, ("rate", residual), "set", ppm_of(re.search(r"scheduled rate of Class AC-\d+ is (\d+\.\d{4}) per cent", body).group(1)))
            tab.add(True, num, ("export", residual), "set", "are not excluded" not in body)
            tab.add(True, num, ("band", residual), "set", re.search(r"assigned to Band (I{1,3})\.", body).group(1))
            continue
        if part in (7, 13, 14) and not div.startswith("Division 7-0"):
            read_modifier(num, body, tab, corrections)

    # corrections (Division 7-2) act in place on the provision they name
    every = tab.original + tab.modifying
    for num, target, old, new in corrections:
        target_sec = target.split("(")[0]
        if target_sec == "11-010":
            hits = [p for p in tab.original if p[0] == target_sec and p[1] == ("minimum", "trust")]
        else:
            hits = [p for p in every if p[0] == target_sec and value_text(p[1], p[3]) == old]
        for p in hits:
            p[3] = parse_like(p[1], new)
            p[5] = num

    # provisions that name a credit by its section
    code_of_section = {spec["section"]: code for code, spec in credits.items()}
    for p in tab.modifying:
        if p[1][0] in ("cap_basis", "cap_amount", "carry_of_section"):
            code = code_of_section[p[1][1]]
            p[1] = ({"cap_basis": "credit_cap", "cap_amount": "credit_cap", "carry_of_section": "credit_carry"}[p[1][0]], code)
            if p[2] == "set" and p[1][0] == "credit_cap":
                p[2] = "cap_basis" if isinstance(p[3], str) else "cap_amount"

    scalar: dict[tuple, list] = {}
    for p in sorted(tab.original, key=lambda p: sec_order(p[0])) + sorted(tab.modifying, key=lambda p: sec_order(p[0])):
        if p[1][0] in ("rate", "energy", "district", "interest", "group_class", "group_district"):
            continue
        if p[2] == "cap_basis":
            scalar[p[1]] = [(p[3], scalar[p[1]][0][1]), p[5]]
        elif p[2] == "cap_amount":
            scalar[p[1]] = [(scalar[p[1]][0][0], p[3]), p[5]]
        else:
            scalar[p[1]] = [p[3], p[5]]

    # group provisions become per-class / per-district increases at their own section number
    expanded = []
    for p in tab.modifying:
        if p[1][0] == "group_class":
            lo, hi, band, delta = p[3]
            for key, (val, _a) in scalar.items():
                if key[0] == "band" and lo <= int(key[1][3:]) <= hi and val == band:
                    code = key[1]
                    expanded.append([p[0], ("rate", code), "add", delta, p[4], p[5]])
        elif p[1][0] == "group_district":
            region, delta = p[3]
            for key, (val, _a) in scalar.items():
                if key[0] == "region" and val == region and scalar[("edz", key[1])][0]:
                    code = key[1]
                    expanded.append([p[0], ("district", code), "add", delta, p[4], p[5]])
        else:
            expanded.append(p)

    quarterly: dict[tuple, dict[str, list]] = {}
    dated: dict[tuple, list[list]] = {}
    ordered = sorted(tab.original, key=lambda p: sec_order(p[0])) + sorted(expanded, key=lambda p: sec_order(p[0]))
    for num, key, op, value, start, auth in ordered:
        if key[0] in ("rate", "energy"):
            series = quarterly.setdefault(key, {})
            qs = ["Q1", "Q2", "Q3", "Q4"]
            if start:
                qs = qs[qs.index(QUARTER_OF[(start.month, start.day)]):]
            for q in qs:
                series[q] = [value, auth] if op == "set" else [series[q][0] + value, auth]
        elif key[0] in ("district", "interest"):
            if key not in dated:
                dated[key] = [[LEVY_START, LEVY_END if key[0] == "district" else OPEN, value, auth]]
                continue
            first = start or LEVY_START
            segs = []
            for a, b, v, au in dated[key]:
                nv = value if op == "set" else v + value
                if b < first:
                    segs.append([a, b, v, au])
                elif a >= first:
                    segs.append([a, b, nv, auth])
                else:
                    segs += [[a, first - timedelta(days=1), v, au], [first, b, nv, auth]]
            dated[key] = segs
    return assemble(scalar, quarterly, dated, credits, holidays, residual)


def value_text(key: tuple, value: Any) -> str:
    kind = key[0]
    if kind in ("rate", "surcharge", "coastal_supplement"):
        return f"{value // 10000}.{value % 10000:04d} per cent"
    if kind == "district":
        return f"${value // 100}.{value % 100:02d} per square metre"
    if kind == "payroll_rate":
        return f"{value // 10000}.{(value % 10000) // 100:02d} per cent"
    if kind == "interest":
        return f"{value // 10000}.{(value % 10000) // 100:02d} per cent"
    if kind == "credit_rate":
        return f"{value // 10000} per cent"
    return ""


def parse_like(key: tuple, text: str) -> Any:
    kind = key[0]
    if kind in ("rate", "surcharge", "coastal_supplement", "payroll_rate", "interest", "credit_rate"):
        return ppm_of(text.split(" per cent")[0])
    if kind in ("district", "minimum"):
        return cents_of(text.split(" per")[0])
    raise ValueError(key)


def parse_credit(num: str, body: str) -> dict[str, Any]:
    elig_line = re.search(r"Eligibility\. A filer is eligible (?:for the credit )?if (.*?)\.\n", body).group(1)
    elig: dict[str, Any] = {}
    if elig_line.startswith("its filer class is commercial or mutual"):
        elig = {"classes": ["commercial", "mutual"], "excluded_forms": ["statutory_body"]}
    elif elig_line.startswith("its predominant class is a Band I or Band II"):
        elig = {"bands": ["I", "II"]}
    elif elig_line.startswith("its predominant class is a Band II or Band III"):
        elig = {"bands": ["II", "III"]}
    elif elig_line.startswith("its principal district is a Coastal Zone"):
        elig = {"principal_coastal": True}
    elif elig_line == "its filer class is public":
        elig = {"classes": ["public"]}
    elif elig_line.startswith("its filer class is mutual or its entity form is a cooperative"):
        elig = {"class_or_form": [["mutual"], ["cooperative"]]}
    elif elig_line == "it is a filer":
        elig = {}
    elif elig_line.startswith("at least one of its establishments"):
        elig = {"edz_any": True}
    elif elig_line.startswith("its filer class is commercial and its entity form is a company"):
        elig = {"classes": ["commercial"], "forms": ["company"]}
    elif elig_line.startswith("its activity levy is computed under section 2-040"):
        elig = {"small_enterprise": True}
    elif elig_line.startswith("its principal district is an Enterprise Development Zone district and is not a Coastal"):
        elig = {"principal_edz": True, "principal_not_coastal": True}
    else:
        raise ValueError(elig_line)
    amount = re.search(r"Amount\. The current-year amount of the credit is ([\d.]+) per cent of the (.*?)[.,]", body)
    basis = "claim"
    if "apprentice payroll" in amount.group(2):
        basis = "apprentice_payroll"
    elif "export receipts" in amount.group(2):
        basis = "export_receipts"
    limit = re.search(r"Limit\. The amount of the credit applied (?:for the levy year )?must not exceed (.*?)\.\n", body).group(1)
    cap = cap_of(limit)
    carry_line = re.search(r"Carry-forward period\. (.*)", body).group(1)
    cm = re.search(r"for (\w+) levy years", carry_line)
    carry = WORDS[cm.group(1)] if cm else 0
    code = re.search(r"credit code (K-\d\d)", body).group(1)
    return {"credit_code": code, "section": num, "basis": basis, "eligibility": elig,
            "_rate": ppm_of(amount.group(1)), "_cap": cap, "_carry": carry}


def cap_of(limit: str) -> tuple[str, int]:
    if limit.startswith("$"):
        return ("fixed", cents_of(limit))
    if limit == "the filer's payroll levy":
        return ("payroll_levy", 1000000)
    if limit == "the filer's energy levy":
        return ("energy_levy", 1000000)
    m = re.match(r"([\d.]+) per cent of the filer's (Primary|Gross) Levy", limit)
    return (f"{m.group(2).lower()}_levy", ppm_of(m.group(1)))


def read_modifier(num: str, body: str, tab: Table, corrections: list) -> None:
    text = " ".join(body.split())
    m = re.search(r"The scheduled rate for Class (AC-\d+) \(section [\d-]+\(d\)\) is (\d+\.\d{4}) per cent, with effect from (\d+ \w+ \d{4})", text)
    if not m:
        m2 = re.search(r"With effect from (\d+ \w+ \d{4}), section 2-(\d+)\(d\) has effect as if the scheduled rate stated in it were (\d+\.\d{4}) per cent", text)
        if m2:
            m = (f"AC-{m2.group(2)}", m2.group(3), m2.group(1))
        m3 = re.search(r"With effect from (\d+ \w+ \d{4}), receipts of lines assessed under Class (AC-\d+) bear activity levy at the scheduled rate of (\d+\.\d{4}) per cent", text)
        if m3:
            m = (m3.group(2), m3.group(3), m3.group(1))
    else:
        m = (m.group(1), m.group(2), m.group(3))
    if m:
        tab.add(False, num, ("rate", m[0]), "set", ppm_of(m[1]), parse_date(m[2]))
        return
    m = re.search(r"In section 2-(\d+)\(f\), for 'Band (I{1,3})' substitute 'Band (I{1,3})'", text)
    if m:
        tab.add(False, num, ("band", f"AC-{m.group(1)}"), "set", m.group(3))
        return
    m = re.search(r"aragraph \(e\) of section 2-(\d+)", text)
    if m and "Export receipts" in text:
        tab.add(False, num, ("export", f"AC-{m.group(1)}"), "set", "are not excluded" not in text)
        return
    m = re.search(r"With effect from (\d+ \w+ \d{4}), the establishment levy rate for District (D-\d+) \([^)]*\) under section [\d-]+\(d\) is (\$\d+\.\d{2}) per square metre", text)
    if m:
        tab.add(False, num, ("district", m.group(2)), "set", cents_of(m.group(3)), parse_date(m.group(1)))
        return
    m = re.search(r"In section 6-010, in the entry for the (\w+) region, for '[\d.]+ per cent' substitute '(\d+\.\d{4}) per cent'", text)
    if m:
        tab.add(False, num, ("surcharge", m.group(1)), "set", ppm_of(m.group(2)))
        return
    m = re.search(r"In section 2-040\(1\)\(b\), for '\$[\d,]+' substitute '(\$[\d,]+)'", text)
    if m:
        tab.add(False, num, ("se_threshold",), "set", cents_of(m.group(1)))
        return
    m = re.search(r"With effect from (\d+ \w+ \d{4}), the rate in section 5-010 for (.*?) is (\d+\.\d{3}) cents per kilowatt-hour", text)
    if m:
        tab.add(False, num, ("energy", FUEL_PHRASES[m.group(2)]), "set", mc_of(m.group(3)), parse_date(m.group(1)))
        return
    m = re.search(r"In section 9-(\d+)\(d\), for '(Gross|Primary) Levy' substitute '(Gross|Primary) Levy'", text)
    if m:
        tab.add(False, num, ("cap_basis", f"9-{m.group(1)}"), "set", f"{m.group(3).lower()}_levy")
        return
    m = re.search(r"In section 9-(\d+)\(e\), for '\w+ levy years' substitute '(\w+) levy years'", text)
    if m:
        tab.add(False, num, ("carry_of_section", f"9-{m.group(1)}"), "set", WORDS[m.group(2)])
        return
    m = re.search(r"With effect from (\d+ \w+ \d{4}), the rate of interest under section 12-020 is (\d+\.\d+) per cent per annum", text)
    if m:
        tab.add(False, num, ("interest",), "set", ppm_of(m.group(2)), parse_date(m.group(1)))
        return
    m = re.search(r"With effect from (\d+ \w+ \d{4}), the scheduled rate of every class whose entry is a section numbered from section 2-(\d+) to section 2-(\d+), both inclusive, and which under this Code is assigned to Band (I{1,3}), is increased by (\d+\.\d{4}) percentage points", text)
    if m:
        tab.add(False, num, ("group_class",), "group", (int(m.group(2)), int(m.group(3)), m.group(4), ppm_of(m.group(5))), parse_date(m.group(1)))
        return
    m = re.search(r"With effect from (\d+ \w+ \d{4}), the establishment levy rate for each district of the (\w+) region that is designated an Enterprise Development Zone district is reduced by (\$\d+\.\d{2}) per square metre", text)
    if m:
        tab.add(False, num, ("group_district",), "group", (m.group(2), -cents_of(m.group(3))), parse_date(m.group(1)))
        return
    m = re.search(r"In section 9-001, for '\d+ per cent' substitute '(\d+) per cent'", text)
    if m:
        tab.add(False, num, ("global_cap",), "set", int(m.group(1)))
        return
    m = re.search(r"In section 5-020\(1\), for '\d+ per cent' substitute '(\d+) per cent'", text)
    if m:
        tab.add(False, num, ("band_reduction",), "set", int(m.group(1)))
        return
    m = re.search(r"Notwithstanding section 6-020, for the levy year 2026 the coastal supplement is (\d+\.\d{4}) per cent", text)
    if m:
        tab.add(False, num, ("coastal_supplement",), "set", ppm_of(m.group(1)))
        return
    m = re.search(r"For the levy year 2026 the limit stated in section 9-(\d+)\(d\) is (\$[\d,]+)", text)
    if m:
        tab.add(False, num, ("cap_amount", f"9-{m.group(1)}"), "set", cents_of(m.group(2)))
        return
    if "annual exemption of a mutual-class filer is twice" in text:
        tab.add(False, num, ("mutual_multiplier",), "set", 2)
        return
    for target, old, new in re.findall(r"In section ([\d-]+(?:\(\w\))?)(?:, in the entry for a trust)?, for '([^']+)' read '([^']+)'", text):
        if re.match(r"(2-1|3-1|7-1|4-010|12-020|9-131|11-010)", target):
            corrections.append((num, target, old, new))


def holiday_due_dates(holidays: list[str]) -> dict[str, str]:
    hol = set(holidays)
    out = {}
    for q, nominal in (("Q1", date(2026, 4, 30)), ("Q2", date(2026, 7, 31)), ("Q3", date(2026, 10, 31)), ("Q4", date(2027, 1, 31))):
        while nominal.weekday() > 4 or nominal.isoformat() in hol:
            nominal += timedelta(days=1)
        out[q] = nominal.isoformat()
    return out


def assemble(scalar, quarterly, dated, credits, holidays, residual) -> dict[str, Any]:
    vo = lambda pair: {"value": pair[0], "authority": pair[1]}  # noqa: E731
    qs = ("Q1", "Q2", "Q3", "Q4")
    regions = ("North", "South", "West", "East")
    fuels = ("grid_electricity", "natural_gas", "diesel", "biomass", "solar_onsite")
    forms = ("sole_trader", "partnership", "company", "trust", "cooperative", "statutory_body")
    rules: dict[str, Any] = {"classes": {}, "districts": {}, "residual_class": residual, "holidays": holidays}
    audit: dict[str, Any] = {"activity_classes": {}, "districts": {}, "residual_class": residual}
    for key in sorted(k for k in quarterly if k[0] == "rate"):
        code = key[1]
        band, exp, rates = scalar[("band", code)], scalar[("export", code)], quarterly[key]
        rules["classes"][code] = {"band": band[0], "export_excluded": exp[0],
                                  "rates": {q: {"rate_ppm": rates[q][0], "authority": rates[q][1]} for q in qs}}
        audit["activity_classes"][code] = {"band": vo(band), "export_excluded": vo(exp), "rates_ppm": {q: vo(rates[q]) for q in qs}}
    for key in sorted(k for k in dated if k[0] == "district"):
        code = key[1]
        periods: list[dict[str, Any]] = []
        for a, b, v, au in dated[key]:
            if periods and periods[-1]["rate_cents_per_m2"] == v and periods[-1]["authority"] == au:
                periods[-1]["to"] = b.isoformat()
            else:
                periods.append({"from": a.isoformat(), "to": b.isoformat(), "rate_cents_per_m2": v, "authority": au})
        info = {"region": scalar[("region", code)][0], "coastal": scalar[("coastal", code)][0], "edz": scalar[("edz", code)][0]}
        rules["districts"][code] = dict(info, rate_periods=periods)
        audit["districts"][code] = dict(info, rate_periods=[dict(p) for p in periods])
    rules["regional_surcharge"] = {r: scalar[("surcharge", r)][0] for r in regions}
    audit["regional_surcharge_ppm"] = {r: vo(scalar[("surcharge", r)]) for r in regions}
    rules["coastal_supplement_ppm"] = scalar[("coastal_supplement",)][0]
    audit["coastal_supplement_ppm"] = vo(scalar[("coastal_supplement",)])
    rules["public_floor_factor_percent"] = scalar[("public_factor",)][0]
    audit["public_floor_factor_percent"] = vo(scalar[("public_factor",)])
    rules["payroll"] = {"rate_ppm": scalar[("payroll_rate",)][0], "annual_exemption_cents": scalar[("payroll_exemption",)][0],
                        "mutual_exemption_multiplier": scalar[("mutual_multiplier",)][0], "exempt_forms": ["statutory_body"]}
    audit["payroll_rate_ppm"] = vo(scalar[("payroll_rate",)])
    audit["payroll_annual_exemption_cents"] = vo(scalar[("payroll_exemption",)])
    audit["mutual_exemption_multiplier"] = vo(scalar[("mutual_multiplier",)])
    rules["energy_rates"] = {f: {q: quarterly[("energy", f)][q][0] for q in qs} for f in fuels}
    audit["energy_rates_millicents_per_kwh"] = {f: {q: vo(quarterly[("energy", f)][q]) for q in qs} for f in fuels}
    rules["band_iii_energy_reduction_percent"] = scalar[("band_reduction",)][0]
    audit["band_iii_energy_reduction_percent"] = vo(scalar[("band_reduction",)])
    rules["small_enterprise"] = {"threshold_cents": scalar[("se_threshold",)][0], "rate_factor_percent": scalar[("se_factor",)][0]}
    audit["small_enterprise_threshold_cents"] = vo(scalar[("se_threshold",)])
    audit["small_enterprise_rate_factor_percent"] = vo(scalar[("se_factor",)])
    rules["credits"], audit["credits"] = [], []
    for code, spec in sorted(credits.items(), key=lambda kv: sec_order(kv[1]["section"])):
        rate, cap, carry = scalar[("credit_rate", code)], scalar[("credit_cap", code)], scalar[("credit_carry", code)]
        rules["credits"].append({"credit_code": code, "section": spec["section"], "basis": spec["basis"], "rate_ppm": rate[0],
                                 "cap": {"basis": cap[0][0], "amount": cap[0][1]}, "carry_years": carry[0], "eligibility": spec["eligibility"]})
        audit["credits"].append({"credit_code": code, "section": spec["section"], "rate_ppm": vo(rate),
                                 "cap": {"basis": cap[0][0], "amount": cap[0][1], "authority": cap[1]}, "carry_years": vo(carry)})
    rules["global_credit_cap_percent"] = scalar[("global_cap",)][0]
    audit["global_credit_cap_percent"] = vo(scalar[("global_cap",)])
    rules["minimum_levy_cents"] = {f: scalar[("minimum", f)][0] for f in forms}
    audit["minimum_levy_cents"] = {f: vo(scalar[("minimum", f)]) for f in forms}
    periods = [{"from": a.isoformat(), "to": None if b == OPEN else b.isoformat(), "rate_ppm": v, "authority": au}
               for a, b, v, au in dated[("interest",)]]
    rules["interest_periods"] = [{k: p[k] for k in ("from", "to", "rate_ppm")} for p in periods]
    audit["interest_rate_periods"] = periods
    audit["instalment_due_dates"] = holiday_due_dates(holidays)
    rules["audit"] = audit
    return rules


YEAR_START = date(2026, 1, 1)
YEAR_END = date(2026, 12, 31)
YEAR_DAYS = 365
QUARTERS = ("Q1", "Q2", "Q3", "Q4")
QUARTER_SPAN = {
    "Q1": (date(2026, 1, 1), date(2026, 3, 31)),
    "Q2": (date(2026, 4, 1), date(2026, 6, 30)),
    "Q3": (date(2026, 7, 1), date(2026, 9, 30)),
    "Q4": (date(2026, 10, 1), date(2026, 12, 31)),
}
REGION_NAMES = ("North", "South", "West", "East")
SEGMENT_NAMES = ("commercial", "public")
TOTAL_KEYS = (
    "activity_levy_cents", "floor_levy_cents", "payroll_levy_cents", "energy_levy_cents",
    "surcharge_cents", "primary_levy_cents", "gross_levy_cents", "credits_total_cents",
    "minimum_topup_cents", "net_levy_cents", "payments_cents", "interest_cents", "balance_cents",
)
OUTPUT_NAMES = (
    "summary.json", "policy_audit.json", "data_quality.json",
    "region_North.json", "region_South.json", "region_West.json", "region_East.json",
    "segment_commercial.json", "segment_public.json",
)
FAR_FUTURE = date(2099, 12, 31)


def rhe(num: int, den: int) -> int:
    """Round num/den to the nearest integer, ties to even (section 1-080)."""
    return int((Decimal(num) / Decimal(den)).quantize(Decimal(1), rounding=ROUND_HALF_EVEN))


def rhu(num: int, den: int) -> int:
    """Round num/den to the nearest integer, ties away from zero (section 12-040)."""
    return int((Decimal(num) / Decimal(den)).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def d(text: str) -> date:
    return date.fromisoformat(text)


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def overlap_days(a0: date, a1: date, b0: date, b1: date) -> int:
    lo, hi = max(a0, b0), min(a1, b1)
    return (hi - lo).days + 1 if hi >= lo else 0


def due_dates(rules: dict[str, Any]) -> dict[str, date]:
    holidays = {d(h) for h in rules["holidays"]}
    nominal = {"Q1": date(2026, 4, 30), "Q2": date(2026, 7, 31), "Q3": date(2026, 10, 31), "Q4": date(2027, 1, 31)}
    out = {}
    for q, day in nominal.items():
        while day.weekday() >= 5 or day in holidays:
            day += timedelta(days=1)
        out[q] = day
    return out


def interest_ppm_on(rules: dict[str, Any], day: date) -> int:
    for period in rules["interest_periods"]:
        hi = d(period["to"]) if period["to"] else FAR_FUTURE
        if d(period["from"]) <= day <= hi:
            return period["rate_ppm"]
    raise ValueError(f"no interest rate in force on {day}")


def interest_for(rules: dict[str, Any], amount: int, due: date, until: date) -> int:
    if amount <= 0 or until <= due:
        return 0
    rate_days = 0
    day = due + timedelta(days=1)
    while day <= until:
        rate_days += interest_ppm_on(rules, day)
        day += timedelta(days=1)
    return rhu(amount * rate_days, 1_000_000 * YEAR_DAYS)


def assess(data_dir: Path, rules: dict[str, Any]) -> dict[str, Any]:
    batch = json.loads((data_dir / "batch.json").read_text(encoding="utf-8"))
    assessment_date = d(batch["assessment_date"])
    filers = read_csv(data_dir / "filers.csv")
    establishments = read_csv(data_dir / "establishments.csv")
    receipts = read_csv(data_dir / "receipts.csv")
    payroll = read_csv(data_dir / "payroll.csv")
    energy = read_csv(data_dir / "energy.csv")
    claims = read_csv(data_dir / "credit_claims.csv")
    carries = read_csv(data_dir / "carryforwards.csv")
    payments = read_csv(data_dir / "payments.csv")

    classes = rules["classes"]
    districts = rules["districts"]
    credits = rules["credits"]
    credit_by_code = {c["credit_code"]: c for c in credits}
    residual = rules["residual_class"]
    dues = due_dates(rules)
    issues: list[str] = []

    by_filer: dict[str, dict[str, list[dict[str, str]]]] = {}
    for f in filers:
        by_filer[f["filer_id"]] = {"est": [], "rec": [], "pay": [], "ene": [], "clm": [], "cf": [], "pmt": []}
    for key, rows in (("est", establishments), ("rec", receipts), ("pay", payroll), ("ene", energy),
                      ("clm", claims), ("cf", carries), ("pmt", payments)):
        for row in rows:
            by_filer[row["filer_id"]][key].append(row)

    results: list[dict[str, Any]] = []
    for f in sorted(filers, key=lambda r: r["filer_id"]):
        fid = f["filer_id"]
        recs = by_filer[fid]
        fclass, form = f["filer_class"], f["entity_form"]
        f_start = max(YEAR_START, d(f["commenced_on"]))
        f_end = min(YEAR_END, d(f["ceased_on"])) if f["ceased_on"] else YEAR_END
        active_days = overlap_days(f_start, f_end, YEAR_START, YEAR_END)

        est_period: dict[str, tuple[date, date]] = {}
        est_rows = {e["establishment_id"]: e for e in recs["est"]}
        for e in recs["est"]:
            e_start = max(f_start, d(e["opened_on"]))
            e_end = min(f_end, d(e["closed_on"])) if e["closed_on"] else f_end
            est_period[e["establishment_id"]] = (e_start, e_end)

        # Principal district (Binding Ruling): greatest aggregate floor area among
        # establishments active on at least one day; ties to the lowest code.
        area_by_district: dict[str, int] = {}
        for eid, e in est_rows.items():
            e0, e1 = est_period[eid]
            if e1 >= e0:
                area_by_district[e["district"]] = area_by_district.get(e["district"], 0) + int(e["floor_area_m2"])
        if area_by_district:
            top = max(area_by_district.values())
            principal = min(k for k, v in area_by_district.items() if v == top)
        else:
            principal = f["registered_district"]
        region = districts[principal]["region"]
        coastal = districts[principal]["coastal"]

        # Part 2: activity lines.
        lines = []
        class_totals: dict[str, int] = {}
        export_total = 0
        for r in recs["rec"]:
            reported = r["activity_code"]
            assessed = reported if reported in classes else residual
            if reported not in classes:
                issues.append(f"{fid}/{r['establishment_id']}/{r['quarter']}: unscheduled activity code {reported} assessed under {residual}")
            e0, e1 = est_period[r["establishment_id"]]
            q0, q1 = QUARTER_SPAN[r["quarter"]]
            if overlap_days(e0, e1, q0, q1) == 0:
                issues.append(f"{fid}/{r['establishment_id']}/{r['quarter']}: receipts reported for an inactive establishment")
            gross = int(r["gross_cents"])
            export = int(r["export_cents"])
            export_total += export
            cls = classes[assessed]
            assessable = gross - export if cls["export_excluded"] else gross
            lines.append({"establishment_id": r["establishment_id"], "reported_code": reported,
                          "assessed_code": assessed, "quarter": r["quarter"], "assessable_cents": assessable})
            class_totals[assessed] = class_totals.get(assessed, 0) + max(assessable, 0)
        total_assessable = sum(class_totals.values())
        predominant = None
        if total_assessable > 0:
            top = max(class_totals.values())
            predominant = min(k for k, v in class_totals.items() if v == top)
        band = classes[predominant]["band"] if predominant else None

        se = rules["small_enterprise"]
        small_applied = False
        if f["small_enterprise_election"] == "Y":
            if fclass == "public":
                issues.append(f"{fid}: small enterprise election by a public-class filer disregarded")
            elif total_assessable <= se["threshold_cents"]:
                small_applied = True
        activity_levy = 0
        for line in lines:
            ppm = classes[line["assessed_code"]]["rates"][line["quarter"]]["rate_ppm"]
            if small_applied:
                ppm = ppm * se["rate_factor_percent"] // 100
            levy = rhe(line["assessable_cents"] * ppm, 1_000_000) if line["assessable_cents"] > 0 else 0
            line["rate_ppm"] = ppm
            line["levy_cents"] = levy
            activity_levy += levy
        lines.sort(key=lambda x: (x["establishment_id"], x["quarter"], x["reported_code"]))

        # Part 3 with section 8-020: establishment (floor area) levy.
        floor_levy = 0
        public_factor = rules["public_floor_factor_percent"] if fclass == "public" else 100
        for eid, e in sorted(est_rows.items()):
            e0, e1 = est_period[eid]
            area = int(e["floor_area_m2"])
            for p in districts[e["district"]]["rate_periods"]:
                days = overlap_days(e0, e1, d(p["from"]), d(p["to"]))
                if days:
                    floor_levy += rhe(area * p["rate_cents_per_m2"] * days * public_factor, YEAR_DAYS * 100)

        # Part 4: payroll levy.
        pr = rules["payroll"]
        payroll_base = sum(int(r["payroll_cents"]) - int(r["apprentice_payroll_cents"]) for r in recs["pay"])
        apprentice_total = sum(int(r["apprentice_payroll_cents"]) for r in recs["pay"])
        if form in pr["exempt_forms"]:
            payroll_levy = 0
        else:
            exemption = pr["annual_exemption_cents"] * (pr["mutual_exemption_multiplier"] if fclass == "mutual" else 1)
            exemption = rhe(exemption * active_days, YEAR_DAYS)
            payroll_levy = rhe(max(0, payroll_base - exemption) * pr["rate_ppm"], 1_000_000)

        # Part 5: energy levy.
        energy_gross = 0
        for r in recs["ene"]:
            rate = rules["energy_rates"][r["fuel"]][r["quarter"]]
            energy_gross += rhe(int(r["kwh"]) * rate, 1000)
        reduction = rhe(energy_gross * rules["band_iii_energy_reduction_percent"], 100) if band == "III" else 0
        energy_levy = energy_gross - reduction

        # Part 6: surcharge at the combined rate.
        sur_ppm = rules["regional_surcharge"][region] + (rules["coastal_supplement_ppm"] if coastal else 0)
        surcharge = rhe((activity_levy + floor_levy) * sur_ppm, 1_000_000)
        primary = activity_levy + floor_levy + surcharge
        gross_levy = primary + payroll_levy + energy_levy

        # Part 9 / Part 10: credits and carryforwards.
        edz_any = any(districts[est_rows[eid]["district"]]["edz"] for eid in est_rows
                      if est_period[eid][1] >= est_period[eid][0])
        facts = {"class": fclass, "form": form, "band": band, "small": small_applied, "edz_any": edz_any,
                 "principal_coastal": coastal, "principal_edz": districts[principal]["edz"]}
        claimed: dict[str, int] = {}
        for c in recs["clm"]:
            code = c["credit_code"]
            if code not in credit_by_code:
                issues.append(f"{fid}: claim {c['claim_id']} under {code} disregarded: no such credit")
                continue
            if credit_by_code[code]["basis"] != "claim":
                issues.append(f"{fid}: claim {c['claim_id']} under {code} disregarded: credit arises without claim")
                continue
            claimed[code] = claimed.get(code, 0) + int(c["expenditure_cents"])
        carry_in: dict[str, list[tuple[int, int]]] = {}
        for c in recs["cf"]:
            code, origin, amount = c["credit_code"], int(c["origin_year"]), int(c["remaining_cents"])
            spec = credit_by_code.get(code)
            if spec is None or spec["carry_years"] == 0:
                issues.append(f"{fid}: carryforward {code}/{origin} disregarded: not permitted")
                continue
            if 2026 - origin > spec["carry_years"]:
                issues.append(f"{fid}: carryforward {code}/{origin} disregarded: expired")
                continue
            carry_in.setdefault(code, []).append((origin, amount))

        remaining = gross_levy
        global_room = rhe(gross_levy * rules["global_credit_cap_percent"], 100)
        applied_rows = []
        carry_out = []
        levy_basis = {"primary_levy": primary, "gross_levy": gross_levy, "payroll_levy": payroll_levy,
                      "energy_levy": energy_levy}
        for spec in credits:
            code = spec["credit_code"]
            sources = [(o, a) for o, a in sorted(carry_in.get(code, []))]
            current = 0
            if spec["basis"] == "claim":
                if code in claimed:
                    if eligible(spec, facts):
                        current = rhe(claimed[code] * spec["rate_ppm"], 1_000_000)
                    else:
                        issues.append(f"{fid}: claim under {code} disregarded: filer not eligible")
            elif eligible(spec, facts):
                base = apprentice_total if spec["basis"] == "apprentice_payroll" else export_total
                current = rhe(base * spec["rate_ppm"], 1_000_000)
            if current > 0:
                sources.append((2026, current))
            if not sources:
                continue
            cap = spec["cap"]
            cap_room = cap["amount"] if cap["basis"] == "fixed" else rhe(levy_basis[cap["basis"]] * cap["amount"], 1_000_000)
            for origin, amount in sources:
                take = max(0, min(amount, cap_room, remaining, global_room))
                if take:
                    applied_rows.append({"credit_code": code, "origin_year": origin, "applied_cents": take})
                cap_room -= take
                remaining -= take
                global_room -= take
                left = amount - take
                if left > 0 and spec["carry_years"] > 0 and 2027 - origin <= spec["carry_years"]:
                    carry_out.append({"credit_code": code, "origin_year": origin, "remaining_cents": left})
        credits_total = sum(r["applied_cents"] for r in applied_rows)
        carry_out.sort(key=lambda r: (r["credit_code"], r["origin_year"]))

        # Part 11: minimum levy, prorated (Binding Ruling).
        after_credits = gross_levy - credits_total
        minimum = rhe(rules["minimum_levy_cents"][form] * active_days, YEAR_DAYS)
        topup = max(0, minimum - after_credits)
        net = after_credits + topup

        # Part 12: instalments, payment allocation and interest.
        quarter_amount = net // 4
        inst = [{"quarter": q, "due_date": dues[q], "amount_cents": quarter_amount if q != "Q4" else net - 3 * quarter_amount,
                 "paid_cents": 0, "interest_cents": 0} for q in QUARTERS]
        counted = 0
        for p in sorted(recs["pmt"], key=lambda r: (r["paid_on"], r["payment_id"])):
            paid_on = d(p["paid_on"])
            if paid_on > assessment_date:
                issues.append(f"{fid}: payment {p['payment_id']} dated after the assessment date disregarded")
                continue
            amount = int(p["amount_cents"])
            counted += amount
            for row in inst:
                if amount == 0:
                    break
                open_amount = row["amount_cents"] - row["paid_cents"]
                if open_amount <= 0:
                    continue
                take = min(open_amount, amount)
                row["paid_cents"] += take
                row["interest_cents"] += interest_for(rules, take, row["due_date"], paid_on)
                amount -= take
        for row in inst:
            unpaid = row["amount_cents"] - row["paid_cents"]
            row["interest_cents"] += interest_for(rules, unpaid, row["due_date"], assessment_date)
            row["due_date"] = row["due_date"].isoformat()
        interest = sum(r["interest_cents"] for r in inst)
        balance = net + interest - counted

        results.append({
            "filer_id": fid, "filer_class": fclass, "entity_form": form, "principal_district": principal,
            "region": region, "active_days": active_days, "predominant_class": predominant, "band": band,
            "small_enterprise_applied": small_applied, "activity_lines": lines,
            "activity_levy_cents": activity_levy, "floor_levy_cents": floor_levy, "payroll_levy_cents": payroll_levy,
            "energy_levy_cents": energy_levy, "surcharge_cents": surcharge, "primary_levy_cents": primary,
            "gross_levy_cents": gross_levy, "credits_applied": applied_rows, "credits_total_cents": credits_total,
            "carryforward_out": carry_out, "minimum_levy_cents": minimum, "minimum_topup_cents": topup,
            "net_levy_cents": net, "instalments": inst, "payments_cents": counted, "interest_cents": interest,
            "balance_cents": balance,
        })

    def totals(rows: list[dict[str, Any]]) -> dict[str, int]:
        return {k: sum(r[k] for r in rows) for k in TOTAL_KEYS}

    out: dict[str, Any] = {}
    out["summary.json"] = {
        "report_id": batch["batch_id"],
        "assessment_date": batch["assessment_date"],
        "filer_count": len(results),
        "totals": totals(results),
        "region_totals": {r: totals([x for x in results if x["region"] == r]) for r in REGION_NAMES},
        "class_filer_counts": {c: sum(1 for x in results if x["filer_class"] == c) for c in ("commercial", "mutual", "public")},
        "balance_status_counts": {
            "credit_balance": sum(1 for x in results if x["balance_cents"] < 0),
            "settled": sum(1 for x in results if x["balance_cents"] == 0),
            "balance_due": sum(1 for x in results if x["balance_cents"] > 0),
        },
    }
    out["policy_audit.json"] = dict(rules["audit"], report_id=batch["batch_id"])
    out["data_quality.json"] = {
        "input_file_count": len([p for p in data_dir.iterdir() if p.is_file()]),
        "filer_count": len(filers), "establishment_count": len(establishments),
        "receipts_line_count": len(receipts), "payroll_row_count": len(payroll), "energy_row_count": len(energy),
        "claim_count": len(claims), "carryforward_count": len(carries), "payment_count": len(payments),
        "quality_issue_count": len(issues), "quality_issues": sorted(issues),
    }
    for r in REGION_NAMES:
        members = [x for x in results if x["region"] == r]
        out[f"region_{r}.json"] = {"region": r, "filer_count": len(members), "totals": totals(members),
                                   "filers": [{k: v for k, v in x.items() if k != "region"} for x in members]}
    for s in SEGMENT_NAMES:
        members = [x for x in results if x["filer_class"] == s]
        credit_totals: dict[str, int] = {}
        for x in members:
            for row in x["credits_applied"]:
                credit_totals[row["credit_code"]] = credit_totals.get(row["credit_code"], 0) + row["applied_cents"]
        out[f"segment_{s}.json"] = {"segment": s, "filer_count": len(members), "totals": totals(members),
                                    "credit_totals": credit_totals, "filer_ids": [x["filer_id"] for x in members]}
    return out


def eligible(spec: dict[str, Any], facts: dict[str, Any]) -> bool:
    e = spec["eligibility"]
    if "classes" in e and facts["class"] not in e["classes"]:
        return False
    if "forms" in e and facts["form"] not in e["forms"]:
        return False
    if "excluded_forms" in e and facts["form"] in e["excluded_forms"]:
        return False
    if "bands" in e and facts["band"] not in e["bands"]:
        return False
    if e.get("small_enterprise") and not facts["small"]:
        return False
    if e.get("edz_any") and not facts["edz_any"]:
        return False
    if e.get("principal_coastal") and not facts["principal_coastal"]:
        return False
    if e.get("principal_edz") and not facts["principal_edz"]:
        return False
    if e.get("principal_not_coastal") and facts["principal_coastal"]:
        return False
    if e.get("class_or_form"):
        classes, forms = e["class_or_form"]
        if facts["class"] not in classes and facts["form"] not in forms:
            return False
    return True


def write_outputs(data_dir: Path, out_dir: Path, rules: dict[str, Any]) -> None:
    result = assess(data_dir, rules)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in OUTPUT_NAMES:
        (out_dir / name).write_text(json.dumps(result[name], indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: derive_report.py DATA_DIR OUT_DIR", file=sys.stderr)
        return 2
    batch = Path(argv[1])
    write_outputs(batch, Path(argv[2]), read_rules(batch / "levy_code.md"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
