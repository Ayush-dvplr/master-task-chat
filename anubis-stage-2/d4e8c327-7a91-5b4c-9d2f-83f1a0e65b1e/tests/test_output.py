@criterion(description="The module reaches for the network or hands work to another process instead of deriving the report itself.")
def negative_module_opens_network_or_shells_out(workspace: Path) -> bool:
    def body():
        if not _module(workspace).is_file():
            return False
        tree = ast.parse(_source(workspace))
        banned = {"socket", "urllib", "http", "requests", "ftplib", "telnetlib", "subprocess", "pty"}
        shells = {"system", "popen", "spawnv", "execv"}
        os_names = {"os"}
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                os_names.update(alias.asname for alias in node.names if alias.name == "os" and alias.asname)
        # NEGATIVE: True when the source imports a network or process module or calls an os shell entry point.
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                if any(alias.name.split(".")[0] in banned for alias in node.names):
                    return True
            elif isinstance(node, ast.ImportFrom):
                if node.module and node.module.split(".")[0] in banned:
                    return True
                if node.module == "os" and any(alias.name in shells for alias in node.names):
                    return True
            elif isinstance(node, ast.Attribute) and node.attr in shells:
                owner = node.value
                if isinstance(owner, ast.Name) and owner.id in os_names:
                    return True
                if isinstance(owner, ast.Call) and isinstance(owner.func, ast.Name) and owner.func.id == "__import__":
                    return True
        return False

    return _safe(body)


