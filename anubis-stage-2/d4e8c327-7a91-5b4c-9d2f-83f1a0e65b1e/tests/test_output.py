def _digest(lines):
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()

def _same(got, want):
    """Exact equality that also keeps JSON types apart, so true never stands in for 1."""
    if isinstance(want, bool) or isinstance(got, bool):
        return type(got) is type(want) and got == want
    if isinstance(want, dict):
        return isinstance(got, dict) and set(got) == set(want) and all(_same(got[k], want[k]) for k in want)
    if isinstance(want, list):
        return isinstance(got, list) and len(got) == len(want) and all(_same(a, b) for a, b in zip(got, want))
    if isinstance(want, int):
        return isinstance(got, int) and got == want
    return type(got) is type(want) and got == want


def _whole(value):
    if isinstance(value, bool) or not isinstance(value, int):
        return "invalid"
    return "%d" % value


def _flag(value):
    if value is True:
        return "true"
    if value is False:
        return "false"
    return "invalid"


def _views(out: Path):
    """Canonical pipe-delimited views of the delivered artifacts, used for digest matching."""
