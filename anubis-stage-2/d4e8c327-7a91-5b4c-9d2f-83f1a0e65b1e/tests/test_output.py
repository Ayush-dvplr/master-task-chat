def _matches(out: Path, corpus: str, names) -> bool:
    found = _digests(out)
    wanted = _expected()[corpus]["digests"]
    return all(found[name] == wanted[name] for name in names)


def _document(out: Path, name: str):
    return json.loads((out / ("%s.json" % name)).read_text())


def _outputs(workspace: Path, corpora):
    """Output directories for each named corpus: the delivered one for the shipped corpus,
    a fresh run of the delivered module for an unseen extract. None when a run fails."""
    found = {}
    for corpus in corpora:
        if corpus == "shipped":
            out = _delivered(workspace)
        else:
            result = _run(workspace, corpus)
            if result["code"] != 0:
                return None
            out = result["out"]
        if not _complete(out):
            return None
        found[corpus] = out
    return found


def _views_match(workspace: Path, names, corpora) -> bool:
    found = _outputs(workspace, corpora)
    if found is None:
        return False
    return all(_matches(out, corpus, names) for corpus, out in found.items())


def _keys_match(workspace: Path, document: str, keys, corpora) -> bool:
    found = _outputs(workspace, corpora)
    if found is None:
        return False
    for corpus, out in found.items():
        got = _document(out, document)
        want = _expected()[corpus]["docs"][document]
        if not all(key in got and _same(got[key], want[key]) for key in keys):
            return False
    return True


def _population_matches(out: Path, corpus: str) -> bool:
    return _matches(out, corpus, ["population"])


def _code_literals(workspace: Path):
    """Constants of the module source, leaving out docstrings and bare string statements."""
    tree = ast.parse(_source(workspace))
    skipped = set()
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if isinstance(body, list):
            for statement in body:
                if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant):
                    skipped.add(id(statement.value))
    numbers, strings = [], []
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and id(node) not in skipped:
            if isinstance(node.value, int) and not isinstance(node.value, bool):
                numbers.append(node.value)
            elif isinstance(node.value, str):
                strings.append(node.value)
    return numbers, strings


