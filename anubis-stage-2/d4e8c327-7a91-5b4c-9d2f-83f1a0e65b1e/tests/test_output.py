def _shuffle_rows(directory: Path) -> None:
    """Reorder the data rows of every delimited record file, keeping the comment and header."""
    for path in sorted(directory.iterdir()):
        if path.suffix not in {".csv", ".tsv", ".jsonl"}:
            continue
        lines = path.read_text().splitlines()
        start = 0
        if lines and lines[0].startswith("#"):
            start = 1
        if path.suffix in {".csv", ".tsv"}:
            start += 1
        body = lines[start:]
        if len(body) < 4:
            continue
        middle = len(body) // 2
        rotated = body[middle:] + body[:middle]
        path.write_text("\n".join(lines[:start] + rotated) + "\n")


def _run(workspace: Path, tag: str):
    if tag in _CACHE:
        return _CACHE[tag]
    corpus = tag.split("_")[0]
    result = {"code": -1, "out": None, "data": None, "before": {}, "after": {}}
    module = _module(workspace)
    if not module.is_file():
        _CACHE[tag] = result
        return result
    room = tempfile.mkdtemp(prefix="hold_")
    name = "corpus_%s" % tag.lower() if tag.endswith("named") else "data"
    data = Path(room) / name
    data.mkdir(parents=True, exist_ok=True)
    _unpack(corpus, data)
    if tag.endswith("perm"):
        _shuffle_rows(data)
    if tag.endswith("missing"):
        victim = data / "registry_q3.tsv"
        if victim.is_file():
            victim.unlink()
    out = Path(room) / "out"
    out.mkdir(parents=True, exist_ok=True)
    copy = Path(room) / "apportion_berth.py"
    shutil.copy2(module, copy)
    os.chmod(copy, 0o755)
    for path in sorted(data.iterdir()):
        result["before"][path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
    os.chmod(room, 0o777)
    for path in (data, out):
        os.chmod(path, 0o777)
    command = list(_prefix())
    command.extend([sys.executable, "-I", str(copy), "--data", str(data), "--out", str(out)])
    try:
        process = subprocess.Popen(
            command,
            cwd=room,
            env=dict(_ENV),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            start_new_session=True,
        )
        pgid = None
        try:
            pgid = os.getpgid(process.pid)
        except ProcessLookupError:
            pass
        try:
            process.communicate(timeout=600)
        except subprocess.TimeoutExpired:
            if pgid is not None:
                try:
                    os.killpg(pgid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
            process.communicate()
        result["code"] = process.returncode
    except Exception:
        result["code"] = -1
    finally:
        if "pgid" in dir() and pgid is not None:
            try:
                os.killpg(pgid, signal.SIGKILL)
            except (ProcessLookupError, PermissionError):
                pass
    for path in sorted(data.iterdir()):
        result["after"][path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
    result["out"] = out
    result["data"] = data
    _CACHE[tag] = result
    return result


