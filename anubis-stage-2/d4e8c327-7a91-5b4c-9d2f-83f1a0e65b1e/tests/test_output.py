@criterion(description="Inside each delivered terminal document the cycle grants equal the ledger grants, capacity equals grant plus residual, the binding flag marks a zero residual, claim equals grant plus demurrage and each charterer's running demurrage never falls.")
def cross_artifact_identity_triangle_holds(workspace: Path) -> bool:
    def body():
        out = _delivered(workspace)
        if not _complete(out) or not _population_matches(out, "shipped"):
            return False
        order = {cycle: index for index, cycle in enumerate(_CYCLES)}
        for terminal in _TERMINALS:
            document = _document(out, "terminal_%s" % terminal)
            for cell in document["cycles"]:
                granted = sum(row["granted_hours"] for row in document["ledger"] if row["cycle"] == cell["cycle"])
                if granted != cell["granted_hours"]:
                    return False
                if cell["capacity_hours"] != cell["granted_hours"] + cell["residual_hours"]:
                    return False
                if cell["binding"] is not (cell["residual_hours"] == 0):
                    return False
            seen = {}
            for row in sorted(document["ledger"], key=lambda item: order[item["cycle"]]):
                if row["demurrage_to_date_hours"] < seen.get(row["charterer"], 0):
                    return False
                seen[row["charterer"]] = row["demurrage_to_date_hours"]
                if row["claim_hours"] != row["granted_hours"] + row["demurrage_hours"]:
                    return False
        return True

    return _safe(body)


