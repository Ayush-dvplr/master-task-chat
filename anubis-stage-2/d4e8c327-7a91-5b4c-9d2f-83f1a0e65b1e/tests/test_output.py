def _prefix():
    """Drop privileges where the image allows it, with the group name it actually carries."""
    if "prefix" in _CACHE:
        return _CACHE["prefix"]
    found = []
    if shutil.which("setpriv"):
        for group in ("nogroup", "nobody"):
            trial = ["setpriv", "--reuid=nobody", "--regid=" + group, "--clear-groups", "true"]
            try:
                probe = subprocess.run(trial, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30)
            except Exception:
                continue
            if probe.returncode == 0:
                found = trial[:-1]
                break
    _CACHE["prefix"] = found
    return found


